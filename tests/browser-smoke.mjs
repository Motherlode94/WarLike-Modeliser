import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1280,height:850}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'load'});
 await page.locator('#theme').waitFor({state:'visible'});
 await page.locator('#theme').selectOption('midnight');
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),'midnight');
 await page.reload({waitUntil:'load'});
 assert.equal(await page.locator('#theme').inputValue(),'midnight');
 await page.locator('#tab3d').click();
 assert.equal(await page.locator('#scene').evaluate(el=>el.classList.contains('hidden')),false);
 await page.locator('[data-primitive="cube"]').click();
 await page.locator('[data-primitive="sphere"]').click();
 assert.equal(await page.locator('#modelOutliner button').count(),2);
 await page.locator('[data-transform="position.x"]').fill('2');
 await page.locator('[data-transform="position.x"]').press('Tab');
 assert.equal(await page.locator('[data-transform="position.x"]').inputValue(),'2');
 await page.locator('#modelDuplicate').click();
 assert.equal(await page.locator('#modelOutliner button').count(),3);
 await page.locator('#modelDelete').click();
 assert.equal(await page.locator('#modelOutliner button').count(),2);
 const tabs=page.locator('.model-inspector-tabs');
 await tabs.getByRole('button',{name:'Maillage',exact:true}).click();
 assert.equal(await page.locator('#meshExtrude').isVisible(),true);
 await tabs.getByRole('button',{name:'Surface',exact:true}).click();
 assert.equal(await page.locator('#modelColor').isVisible(),true);
 await tabs.getByRole('button',{name:'Fichiers',exact:true}).click();
 assert.equal(await page.locator('#modelSave').isVisible(),true);
 assert.equal(await page.locator('[data-transform="position.x"]').isVisible(),false);
 const [file]=await Promise.all([page.waitForEvent('download'),page.locator('#modelSave').click()]);
 assert.ok(file.suggestedFilename().endsWith('.modeliser3d.json'));
 await page.locator('#modelFile').setInputFiles(await file.path());
 await page.waitForFunction(()=>document.querySelector('#message').textContent==='Modèle ouvert.');
 assert.equal(await page.locator('#modelOutliner button').count(),2);
 const [glb]=await Promise.all([page.waitForEvent('download'),page.locator('#modelExport').click()]);
 assert.ok(glb.suggestedFilename().endsWith('.glb'));
 const bytes=await readFile(await glb.path());assert.equal(bytes.toString('ascii',0,4),'glTF');assert.equal(bytes.readUInt32LE(4),2);assert.equal(bytes.readUInt32LE(8),bytes.length);
 const jsonLength=bytes.readUInt32LE(12);assert.equal(bytes.readUInt32LE(16),0x4e4f534a);const doc=JSON.parse(bytes.toString('utf8',20,20+jsonLength));assert.equal(doc.asset.version,'2.0');assert.equal(doc.meshes.length,2);assert.ok(doc.meshes.every(m=>m.primitives.every(p=>Number.isInteger(p.attributes.POSITION))));
 const result=await page.evaluate(async data=>{const {GLTFLoader}=await import('three/addons/loaders/GLTFLoader.js');const raw=Uint8Array.from(atob(data),c=>c.charCodeAt(0));const loaded=await new GLTFLoader().parseAsync(raw.buffer,'');let meshes=0;loaded.scene.traverse(o=>{if(o.isMesh)meshes++});return meshes},bytes.toString('base64'));assert.equal(result,2);
 const math=await page.evaluate(async()=>{const THREE=await import('three');const {buildSkinnedMesh,validWeights,assignVertexWeight}=await import('./skin-core.js');const o=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial());const rig=[{name:'Root',position:[0,0,0],rotation:[0,0,0]},{name:'Tip',position:[0,1,0],rotation:[0,0,0]}];const {mesh,bones}=buildSkinnedMesh(o,rig);const g=mesh.geometry;const data={indices:Array.from(g.attributes.skinIndex.array),weights:Array.from(g.attributes.skinWeight.array)};const before=validWeights(data,g.attributes.position.count,bones.length);assignVertexWeight(data,0,1,.75);const after=validWeights(data,g.attributes.position.count,bones.length);const assigned=data.indices[0]===1&&Math.abs(data.weights[0]-.75)<1e-6;mesh.skeleton.dispose();g.dispose();mesh.material.dispose();o.geometry.dispose();o.material.dispose();return {before,after,assigned}});assert.deepEqual(math,{before:true,after:true,assigned:true},'automatic and edited skin weights normalized');
 await page.locator('#tab2d').click();
 assert.equal(await page.locator('#canvas').evaluate(el=>el.classList.contains('hidden')),false);
 assert.deepEqual(errors,[],'unexpected Modeliser JavaScript errors');
 console.log('PASS: Modeliser boot, theme persistence, 2D/3D switching');
}finally{await browser.close()}
